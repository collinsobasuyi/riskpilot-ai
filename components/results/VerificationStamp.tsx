"use client";

import React, { useEffect, useState } from "react";
import { ShieldCheck } from "lucide-react";
import { AssessmentFormData } from "../../lib/risk/schema";

async function sha256Hex(text: string): Promise<string> {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(text));
  return Array.from(new Uint8Array(digest))
    .map((b) => b.toString(16).padStart(2, "0"))
    .join("");
}

export function VerificationStamp({
  data,
  reportId,
  generatedOn,
}: {
  data: AssessmentFormData;
  reportId: string;
  generatedOn: string;
}) {
  const [hash, setHash] = useState<string | null>(null);

  useEffect(() => {
    sha256Hex(JSON.stringify(data)).then(setHash).catch(() => setHash(null));
  }, [data]);

  const rows = [
    { label: "Report ID", value: reportId },
    { label: "Generated by", value: "Verdictal" },
    { label: "Generated on", value: generatedOn },
    { label: "Report status", value: "Prototype – Validation only" },
    {
      label: "Verification reference",
      value: hash ? `sha256_${hash.slice(0, 16)}…` : "Computing…",
    },
  ];

  return (
    <div className="rounded-sm border border-slate-300 bg-slate-50 p-5">
      <div className="flex items-center gap-2">
        <ShieldCheck className="h-4 w-4 text-blue-700" />
        <p className="text-sm font-semibold uppercase tracking-widest text-slate-600">
          Report Verification
        </p>
      </div>
      <p className="mt-2 text-sm text-slate-600 leading-relaxed">
        This prototype report includes a verification reference (a SHA-256 fingerprint of the
        assessment data) to support future evidence integrity and audit traceability.
      </p>
      <dl className="mt-4 grid grid-cols-1 gap-x-8 gap-y-2 sm:grid-cols-2">
        {rows.map((row) => (
          <div key={row.label} className="flex items-baseline gap-2">
            <dt className="text-xs font-semibold text-slate-500">{row.label}:</dt>
            <dd className="font-mono text-xs text-slate-700">{row.value}</dd>
          </div>
        ))}
      </dl>
      <p className="mt-3 text-xs text-slate-400">
        Evidence integrity: prototype verification only. Immutable audit storage is not yet
        enabled.
      </p>
    </div>
  );
}
