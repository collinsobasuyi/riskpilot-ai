import React from "react";
import { Shield } from "lucide-react";
import { ComputedResults } from "../../lib/risk/scoring";
import { ReadinessStatus } from "../../lib/risk/insurance";

const READINESS_BADGE: Record<"green" | "amber" | "red", string> = {
  green: "bg-green-500/20 text-green-300",
  amber: "bg-amber-500/20 text-amber-300",
  red: "bg-red-500/20 text-red-300",
};

function Meta({ label, value }: { label: string; value: string }) {
  return (
    <div>
      <dt className="text-[10px] font-semibold uppercase tracking-widest text-slate-400">
        {label}
      </dt>
      <dd className="mt-0.5 text-sm font-medium text-white">{value}</dd>
    </div>
  );
}

export function ReportHeader({
  systemName,
  companyName,
  industry,
  assessmentDate,
  results,
  scoreDelta,
  readiness,
}: {
  systemName: string;
  companyName: string;
  industry?: string;
  assessmentDate: string;
  results: ComputedResults;
  scoreDelta?: number;
  readiness?: { status: ReadinessStatus; statusColor: "green" | "amber" | "red" };
}) {
  const scoreColor =
    results.riskScore >= 70
      ? "text-red-400"
      : results.riskScore >= 45
      ? "text-amber-400"
      : "text-green-400";

  const tierColor =
    results.riskLevel === "High"
      ? "bg-red-500/20 text-red-300"
      : results.riskLevel === "Medium"
      ? "bg-amber-500/20 text-amber-300"
      : "bg-green-500/20 text-green-300";

  return (
    <div className="bg-slate-900 rounded-sm px-6 py-6 sm:px-8 print:bg-slate-800">
      {/* Title row */}
      <div className="flex items-center justify-between border-b border-slate-700 pb-4">
        <div className="flex items-center gap-2.5">
          <Shield className="h-5 w-5 text-blue-400" />
          <span className="text-base font-semibold text-white">
            Verdictal AI Risk Evidence Report
          </span>
        </div>
        <span className="rounded-sm border border-slate-600 px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wider text-slate-300">
          Prototype · Validation only
        </span>
      </div>

      {/* Metadata grid */}
      <dl className="mt-5 grid grid-cols-2 gap-x-8 gap-y-4 sm:grid-cols-3">
        <Meta label="Client" value={companyName} />
        <Meta label="AI system" value={systemName} />
        {industry && <Meta label="Sector" value={industry} />}
        <Meta label="Report type" value="Insurance Readiness Review" />
        <Meta label="Generated" value={assessmentDate} />
        <Meta label="Generated by" value="Verdictal" />
      </dl>

      {/* Score row */}
      <div className="mt-6 flex items-end gap-3 flex-wrap border-t border-slate-700 pt-5">
        <div>
          <p className="text-[10px] font-semibold uppercase tracking-widest text-slate-400">
            AI Risk Score
          </p>
          <span className={`text-5xl font-bold ${scoreColor}`}>{results.riskScore}</span>
        </div>
        <div className="mb-1 flex items-center gap-2 flex-wrap">
          <span className="text-slate-400 text-sm">/100</span>
          <div className={`inline-flex items-center rounded-sm px-2 py-0.5 text-xs font-semibold ${tierColor}`}>
            {results.riskLevel} Risk
          </div>
          {readiness && (
            <div className={`inline-flex items-center rounded-sm px-2 py-0.5 text-xs font-semibold ${READINESS_BADGE[readiness.statusColor]}`}>
              {readiness.status}
            </div>
          )}
          <div className="inline-flex items-center rounded-sm bg-slate-500/20 px-2 py-0.5 text-xs font-semibold text-slate-300">
            {results.coverageTier} underwriting
          </div>
          {/* Risk score: higher is worse, so an increase is red and a drop is green */}
          {scoreDelta !== undefined && (
            <span className={`inline-flex items-center rounded-sm px-2 py-0.5 text-xs font-bold ${
              scoreDelta > 0
                ? "bg-red-500/20 text-red-300"
                : scoreDelta < 0
                ? "bg-green-500/20 text-green-300"
                : "bg-slate-500/20 text-slate-400"
            }`}>
              {scoreDelta > 0 ? `↑ +${scoreDelta}` : scoreDelta < 0 ? `↓ ${scoreDelta}` : "= no change"} since last
            </span>
          )}
        </div>
      </div>
      <p className="mt-2 text-xs text-slate-400">Valid until {results.validUntil}</p>
      <p className="mt-4 border-t border-slate-700 pt-3 text-xs text-slate-400">
        This report is designed to support insurance, audit, compliance, and enterprise risk
        review.
      </p>
    </div>
  );
}
